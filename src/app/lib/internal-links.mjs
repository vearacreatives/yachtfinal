  const stop = new Set(['goa','yacht','yachts','the','a','an','in','on','of','for','to','and','with','your','why','how','is']);
  const tokens = s => new Set(s.split('-').filter(t => !stop.has(t)));
  const source = tokens(slug);
  const ranked = ARTICLES.filter(a => a.slug !== slug).map(a => ({...a, score: [...tokens(a.slug)].filter(t => source.has(t)).length})).sort((a,b) => b.score-a.score || a.slug.localeCompare(b.slug));
  const choices = [...(topic?.guides || []), ...ranked.filter(a=>a.score>0).map(a=>a.slug), ...DEFAULT_GUIDES];
